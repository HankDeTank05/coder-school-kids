#pieces
PIECES_SIZE = 140

#board stuff
MIN_WIN_LENGTH = 4
X_EDGE_SPACING = 40
Y_EDGE_SPACING = 5
X_CIRCLE_SPACING = 2
Y_CIRCLE_SPACING = 2

# auto-calculate board size
STANDARD_COL_COUNT = 7
STANDARD_ROW_COUNT = 6

PLAYER_COUNT = 2
MIN_PLAYER_COUNT = 2
assert(PLAYER_COUNT >= MIN_PLAYER_COUNT)
assert(PLAYER_COUNT % 1 == 0) # if you triggered this assertion, you're a dirty scoundrel trying to have a fraction of a team

COL_SCALING_PER_TEAM = 3
ROW_SCALING_PER_TEAM = 2
COL_COUNT = STANDARD_COL_COUNT + (PLAYER_COUNT - MIN_PLAYER_COUNT) * COL_SCALING_PER_TEAM
ROW_COUNT = STANDARD_ROW_COUNT + (PLAYER_COUNT - MIN_PLAYER_COUNT) * ROW_SCALING_PER_TEAM

# auto-calculate circle radius
CIRCLE_RADIUS_FROM_WIDTH = (WIDTH - (2 * X_EDGE_SPACING) - ((COL_COUNT - 1) * X_CIRCLE_SPACING)) / 2 / COL_COUNT
CIRCLE_RADIUS_FROM_HEIGHT = (HEIGHT - (2 * Y_EDGE_SPACING) - ((ROW_COUNT - 1) * Y_CIRCLE_SPACING)) / 2 / ROW_COUNT
if CIRCLE_RADIUS_FROM_WIDTH < CIRCLE_RADIUS_FROM_HEIGHT:
    CIRCLE_RADIUS = CIRCLE_RADIUS_FROM_WIDTH
    assert(WIDTH == (2 * X_EDGE_SPACING) + ((COL_COUNT - 1) * X_CIRCLE_SPACING) + (COL_COUNT * 2 * CIRCLE_RADIUS))
else:
    CIRCLE_RADIUS = CIRCLE_RADIUS_FROM_HEIGHT
    assert(HEIGHT == (2 * Y_EDGE_SPACING) + ((ROW_COUNT - 1) * Y_CIRCLE_SPACING) + (ROW_COUNT * 2 * CIRCLE_RADIUS))